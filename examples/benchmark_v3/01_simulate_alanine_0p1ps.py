# -*- coding: utf-8 -*-
"""
Generate 0.1 ps burst endpoints for alanine dipeptide (multi-tau benchmark).

Reuses the existing 1578 anchors from alanine_koopman.npz (which were
generated by the 5 ps MetaD protocol).  Only the burst propagation step
is repeated here, with LAG_PS = 0.1 (50 steps at 2 fs).

Output
------
  data/alanine_0p1ps_koopman.npz
    bursts_feat  (1578, 20, 231)  — pairwise-distance features at t+0.1ps
    bursts_phi   (1578, 20)
    bursts_psi   (1578, 20)
    anchors_cart (1578, 22, 3)    — copy from parent file (for provenance)
    lag_ps       (1,)             — 0.1
    temp_K       (1,)             — 450.0
"""

import os
import sys
import numpy as np

import openmm as mm
from openmm import app, unit

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "..", "src"))
from amore.sims.openmm_sim import DEFAULT_PDB, FORCE_AMBER

DATADIR = os.path.join(os.path.dirname(__file__), "..", "benchmark", "data")

TEMP      = 450.0    # K — must match parent simulation
DT        = 2e-3     # ps (2 fs)
FRICTION  = 1.0      # ps⁻¹
LAG_PS    = 0.1
N_BURSTS  = 20
BURST_STEPS = int(LAG_PS / DT)   # 50 steps

_PHI_IDX = (4, 6, 8, 14)
_PSI_IDX = (6, 8, 14, 16)
N_ATOMS  = 22
PAIRS    = [(i, j) for i in range(N_ATOMS) for j in range(i + 1, N_ATOMS)]


def compute_phi_psi(pos_nm):
    def dihedral(p0, p1, p2, p3):
        b1 = p1 - p0; b2 = p2 - p1; b3 = p3 - p2
        n1 = np.cross(b1, b2); n2 = np.cross(b2, b3)
        n1 /= np.linalg.norm(n1) + 1e-12
        n2 /= np.linalg.norm(n2) + 1e-12
        m = np.cross(n1, b2 / (np.linalg.norm(b2) + 1e-12))
        return np.arctan2(m @ n2, n1 @ n2)
    p = pos_nm
    phi = dihedral(p[_PHI_IDX[0]], p[_PHI_IDX[1]], p[_PHI_IDX[2]], p[_PHI_IDX[3]])
    psi = dihedral(p[_PSI_IDX[0]], p[_PSI_IDX[1]], p[_PSI_IDX[2]], p[_PSI_IDX[3]])
    return float(phi), float(psi)


def pairwise_distances(pos_nm):
    return np.array([np.linalg.norm(pos_nm[i] - pos_nm[j]) for i, j in PAIRS],
                    dtype=np.float32)


# ── Load existing anchors ─────────────────────────────────────────────────────
parent_path = os.path.join(DATADIR, "alanine_koopman.npz")
assert os.path.exists(parent_path), f"Parent file not found: {parent_path}"
parent = np.load(parent_path)
anchor_cart = parent["anchors_cart"]   # (1578, 22, 3)
N_ANC = len(anchor_cart)
print(f"Loaded {N_ANC} anchors from {parent_path}")
print(f"Burst lag: {LAG_PS} ps  ({BURST_STEPS} steps at {DT*1000:.0f} fs)")


# ── Build unbiased OpenMM simulation ─────────────────────────────────────────
print("Building OpenMM system (450 K, vacuum, AMBER14) ...")
pdb_obj    = app.PDBFile(DEFAULT_PDB)
forcefield = app.ForceField(*FORCE_AMBER)
modeller   = app.Modeller(pdb_obj.topology, pdb_obj.positions)
system     = forcefield.createSystem(modeller.topology,
                                     nonbondedMethod=app.NoCutoff,
                                     removeCMMotion=False)
integrator = mm.LangevinMiddleIntegrator(
    TEMP * unit.kelvin, FRICTION / unit.picosecond, DT * unit.picoseconds
)
sim = app.Simulation(modeller.topology, system, integrator)


# ── Burst propagation ─────────────────────────────────────────────────────────
out_path = os.path.join(DATADIR, "alanine_0p1ps_koopman.npz")
if os.path.exists(out_path):
    print(f"Output already exists: {out_path}  (delete to regenerate)")
    sys.exit(0)

print(f"Propagating {N_ANC} x {N_BURSTS} bursts ({BURST_STEPS} steps each) ...")
bursts_feat = np.empty((N_ANC, N_BURSTS, len(PAIRS)), dtype=np.float32)
bursts_phi  = np.empty((N_ANC, N_BURSTS), dtype=np.float32)
bursts_psi  = np.empty((N_ANC, N_BURSTS), dtype=np.float32)

for i, pos0 in enumerate(anchor_cart):
    pos0_q = (pos0 * unit.nanometer).tolist()
    for k in range(N_BURSTS):
        sim.context.setPositions(pos0_q)
        sim.context.setVelocitiesToTemperature(TEMP * unit.kelvin)
        sim.step(BURST_STEPS)
        state = sim.context.getState(getPositions=True)
        pos1  = np.array(state.getPositions(asNumpy=True).value_in_unit(unit.nanometer),
                         dtype=np.float32)
        bursts_feat[i, k] = pairwise_distances(pos1)
        bursts_phi[i, k], bursts_psi[i, k] = compute_phi_psi(pos1)
    if (i + 1) % 200 == 0:
        print(f"  anchor {i+1}/{N_ANC}")

print("Done propagating.")

np.savez(
    out_path,
    bursts_feat  = bursts_feat,
    bursts_phi   = bursts_phi,
    bursts_psi   = bursts_psi,
    anchors_cart = anchor_cart,
    lag_ps       = np.array([LAG_PS]),
    temp_K       = np.array([TEMP]),
)
print(f"Saved: {out_path}")
print(f"  bursts_feat = {bursts_feat.shape}")
